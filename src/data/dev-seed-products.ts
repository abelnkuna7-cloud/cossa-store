interface SeedInput {
  sku: string;
  name: string;
  category: CategorySlug;
  subcategory: string;
  brand: string;
  price: number;
  compare?: number;
  short: string;
  full: string;
  stock: StockStatus;
  qty: number | null;
  fulfilment: FulfilmentType;
  delivery: string;
  specs: [string, string][];
  features: string[];
  warranty?: string;
}

const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const TIMESTAMP = "2025-01-06T08:00:00.000Z";

function build(seed: SeedInput, index: number): Product {
  const slug = slugify(seed.name);
  return {
    id: `seed-${index + 1}`,
    sku: seed.sku,
    name: seed.name,
    slug,
    short_description: seed.short,
    full_description: seed.full,
    category: seed.category,
    subcategory: seed.subcategory,
    brand: seed.brand,
    supplier_id: null,
    supplier_sku: null,
    cost_price: null,
    selling_price: seed.price,
    compare_at_price: seed.compare ?? null,
    vat_status: "vat_inclusive",
    stock_status: seed.stock,
    stock_quantity: seed.qty,
    fulfilment_type: seed.fulfilment,
    estimated_delivery: seed.delivery,
    images: [{ url: null, alt: seed.name }],
    specifications: seed.specs.map(([label, value]) => ({ label, value })),
    features: seed.features,
    warranty: seed.warranty ?? null,
    return_eligibility: "Returnable within 7 days if unused and in original packaging.",
    status: "active",
    seo_title: `${seed.name} | Cossa Store`,
    seo_description: seed.short,
    created_at: TIMESTAMP,
    updated_at: TIMESTAMP,
  };
}

